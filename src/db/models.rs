//! Row-mirroring types and insertion/update inputs for the data layer.
//!
//! These structs are **internal**: they mirror the SQLite schema one-to-one and
//! are populated by `sqlx::FromRow`. They are not the public REST DTOs (that is
//! F06); the SPA-facing shapes will be derived from these later.

use sqlx::FromRow;

/// Kind of a DAV collection, constrained by the schema's `CHECK` clause.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CollectionKind {
    /// A CalDAV calendar.
    Calendar,
    /// A CardDAV address book.
    Addressbook,
}

impl CollectionKind {
    /// The exact string stored in `collections.type`.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Calendar => "calendar",
            Self::Addressbook => "addressbook",
        }
    }
}

/// A row of `collections`.
#[derive(Debug, Clone, FromRow)]
pub struct Collection {
    /// Primary key (UUID-ish string generated by the caller).
    pub id: String,
    /// Pocket ID `sub` claim of the owner.
    pub user_id: String,
    /// Human-readable name.
    pub name: String,
    /// `calendar` or `addressbook` (column `type`).
    #[sqlx(rename = "type")]
    pub kind: String,
    /// UI accent colour.
    pub color: String,
    /// Monotonic change token for RFC 6578 `sync-collection`.
    pub sync_token: i64,
    /// Creation time, Unix milliseconds.
    pub created_at: i64,
    /// Last modification time, Unix milliseconds.
    pub updated_at: i64,
}

/// Input for creating a collection.
#[derive(Debug, Clone)]
pub struct NewCollection {
    /// Primary key.
    pub id: String,
    /// Pocket ID `sub` claim of the owner.
    pub user_id: String,
    /// Human-readable name.
    pub name: String,
    /// Calendar or address book.
    pub kind: CollectionKind,
    /// UI accent colour.
    pub color: String,
}

