/// Kind of change recorded in `sync_log`, constrained by the schema's `CHECK`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, sqlx::Type)]
#[sqlx(rename_all = "lowercase")]
pub enum ChangeKind {
    /// A resource was created.
    Added,
    /// An existing resource was modified.
    Updated,
    /// A resource was removed (tombstone: the object is gone, the log survives).
    Deleted,
}

impl ChangeKind {
    /// The exact string stored in `sync_log.change`.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Added => "added",
            Self::Updated => "updated",
            Self::Deleted => "deleted",
        }
    }

    /// Parse the database string form; `None` for an unknown value.
    #[must_use]
    pub fn from_db(value: &str) -> Option<Self> {
        match value {
            "added" => Some(Self::Added),
            "updated" => Some(Self::Updated),
            "deleted" => Some(Self::Deleted),
            _ => None,
        }
    }
}

/// Kind of DAV resource a change refers to, constrained by the schema's `CHECK`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, sqlx::Type)]
#[sqlx(rename_all = "lowercase")]
pub enum ResourceKind {
    /// A `.ics` calendar object.
    Calendar,
    /// A `.vcf` card object.
    Card,
}

impl ResourceKind {
    /// The exact string stored in `sync_log.resource_kind`.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Calendar => "calendar",
            Self::Card => "card",
        }
    }

    /// Parse the database string form; `None` for an unknown value.
    #[must_use]
    pub fn from_db(value: &str) -> Option<Self> {
        match value {
            "calendar" => Some(Self::Calendar),
            "card" => Some(Self::Card),
            _ => None,
        }
    }
}

/// A single entry of the change log as reported by `sync-collection`.
///
/// `etag` is `Some` for live resources (`added`/`updated`) and `None` for a
/// `deleted` tombstone (the object no longer exists, so no ETag can be given).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SyncChange {
    /// DAV `UID` of the affected resource.
    pub resource_uid: String,
    /// Whether the resource is a calendar or card object.
    pub resource_kind: ResourceKind,
    /// The most recent change kind for this resource in the queried interval.
    pub change: ChangeKind,
    /// Value of `collections.sync_token` this change was recorded at.
    pub sync_token: i64,
    /// Current ETag, or `None` for a tombstone.
    pub etag: Option<String>,
}
